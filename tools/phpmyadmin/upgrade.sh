#!/bin/bash
# phpMyAdmin upgrade script (invoked by the zap appstore)
#
# Injected environment variables (provided by zapexec): ZAP_PATH APPS_DIR APP_PATH BUILD_PATH ZAP_DATA_PATH
#                                                       APP_VERSION MAJOR_VERSION MINOR_VERSION APP_OLD_VERSION
# Options (app.yaml options.upgrade):
#   PHP_VERSION   PHP to use after upgrade (auto = chosen by zapd on each request)
#
# Strategy: keep config.inc.php (blowfish_secret and server settings), replace the program files;
#           the /usr/local/apps/phpmyadmin symlink switches to the new version directory, so the
#           access entry point stays unchanged.
set -euo pipefail

source "${ZAP_PATH}/scripts/zap/bash_utils.sh"
assert_root || exit 1

APP_TITLE="phpMyAdmin"
VERSION="${APP_VERSION:-}"
[ -n "${VERSION}" ] || { log_error "Missing APP_VERSION, cannot upgrade"; exit 1; }
S_VERSION="${MAJOR_VERSION:-}.${MINOR_VERSION:-}"
[ "${S_VERSION}" != "." ] || { log_error "Cannot parse version: APP_VERSION=${VERSION}"; exit 1; }

OLD_VERSION="${APP_OLD_VERSION:-unknown}"

INSTALL_DIR="${APPS_DIR}/phpmyadmin-${S_VERSION}"
LINK_DIR="${APPS_DIR}/phpmyadmin"
LOG_DIR="${ZAP_DATA_PATH}/logs"

log_info "Preparing to upgrade ${APP_TITLE}: ${OLD_VERSION} -> ${VERSION}"

# ── locate the old install dir & config ────────────────────────────────────
OLD_DIR=""
INFO_FILE="${APP_PATH}/info.yaml"
if [ -f "${INFO_FILE}" ]; then
    OLD_DIR="$(grep -m1 '^install_dir:' "${INFO_FILE}" 2>/dev/null | sed 's/^install_dir:[[:space:]]*//' || true)"
fi
[ -n "${OLD_DIR}" ] || OLD_DIR="${LINK_DIR}"

# The old config (blowfish_secret / DB host) MUST be reused; otherwise all logged-in sessions
# and cookies become invalid
OLD_CONF=""
if [ -f "${OLD_DIR}/config.inc.php" ]; then
    OLD_CONF="${OLD_DIR}/config.inc.php"
elif [ -f "${LINK_DIR}/config.inc.php" ]; then
    OLD_CONF="${LINK_DIR}/config.inc.php"
fi

# ── download & extract the new version ────────────────────────────────────────
ARCHIVE="phpMyAdmin-${VERSION}-all-languages.tar.gz"
URL="https://files.phpmyadmin.net/phpMyAdmin/${VERSION}/${ARCHIVE}"

rm -rf "${BUILD_PATH}"
ensure_dir "${BUILD_PATH}"
download_file "${URL}" "${BUILD_PATH}/${ARCHIVE}"
extract_archive "${BUILD_PATH}/${ARCHIVE}" "${BUILD_PATH}" || {
    log_error "Extraction failed: ${ARCHIVE}"
    exit 1
}

SRC_DIR="${BUILD_PATH}/phpMyAdmin-${VERSION}-all-languages"
if [ ! -d "${SRC_DIR}" ]; then
    SRC_DIR="$(find "${BUILD_PATH}" -maxdepth 1 -mindepth 1 -type d | head -n1)"
fi
[ -d "${SRC_DIR}" ] || { log_error "Unexpected extraction result: source directory not found"; exit 1; }

# ── deploy the new version ──────────────────────────────────────────────
rm -rf "${INSTALL_DIR}"
ensure_dir "$(dirname "${INSTALL_DIR}")"
mv "${SRC_DIR}" "${INSTALL_DIR}"
log_ok "Program deployed to: ${INSTALL_DIR}"

# ── restore config ────────────────────────────────────────────────
ensure_dir "${INSTALL_DIR}/tmp" "${INSTALL_DIR}/upload" "${INSTALL_DIR}/save"
if [ -n "${OLD_CONF}" ] && [ -f "${OLD_CONF}" ]; then
    cp -f "${OLD_CONF}" "${INSTALL_DIR}/config.inc.php"
    log_ok "Reused the existing config.inc.php"
else
    SECRET="$(random_password 32 | tr -d '\n')"
    cat >"${INSTALL_DIR}/config.inc.php" <<EOF
<?php
/**
 * phpMyAdmin config (generated by the ZAP appstore)
 * Generated at: $(date '+%Y-%m-%d %H:%M:%S')
 */
declare(strict_types=1);

\$cfg['blowfish_secret'] = '${SECRET}';
\$cfg['DefaultLang'] = 'zh_CN';
\$cfg['TempDir'] = '${LINK_DIR}/tmp';
\$cfg['UploadDir'] = '${LINK_DIR}/upload';
\$cfg['SaveDir'] = '${LINK_DIR}/save';

\$i = 0;
\$i++;
\$cfg['Servers'][\$i]['host'] = '127.0.0.1';
\$cfg['Servers'][\$i]['port'] = '3306';
\$cfg['Servers'][\$i]['auth_type'] = 'cookie';
\$cfg['Servers'][\$i]['AllowNoPassword'] = false;
EOF
    log_warn "Existing config not found; generated a default config.inc.php"
fi

# ── switch the symlink ────────────────────────────────────────────────
ln -sfn "${INSTALL_DIR}" "${LINK_DIR}"
log_ok "Symlink switched: ${LINK_DIR} -> ${INSTALL_DIR}"

# ── runtime user & permissions ──────────────────────────────────────────
RUN_USER="www"
id -u www >/dev/null 2>&1 || RUN_USER="nginx"
id -u "${RUN_USER}" >/dev/null 2>&1 || RUN_USER="$(id -un)"
chown -R "${RUN_USER}" "${INSTALL_DIR}" 2>/dev/null || log_warn "Failed to change owner (user ${RUN_USER})"
find "${INSTALL_DIR}" -type d -exec chmod 0755 {} + 2>/dev/null || true
find "${INSTALL_DIR}" -type f -exec chmod 0644 {} + 2>/dev/null || true
chmod 0770 "${INSTALL_DIR}/tmp" "${INSTALL_DIR}/upload" "${INSTALL_DIR}/save" 2>/dev/null || true

# ── site config: leave untouched by default, rebuild only when PHP is explicit ───────────
# The access channel is served by zapd's /webapps/phpmyadmin/ (panel auth + FastCGI straight to
# the system PHP-FPM): we no longer generate a standalone Nginx site, to avoid exposing an
# unauthenticated database entry point.
log_info "The PHP channel is resolved by zapd on each request; no site config rebuild needed"

# ── update registered info ────────────────────────────────────────────
HOST_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
[ -n "${HOST_IP}" ] || HOST_IP="$(ip route get 1 2>/dev/null | awk '{print $7; exit}')"
[ -n "${HOST_IP}" ] || HOST_IP="127.0.0.1"
PORT_SHOW="$(grep -m1 '^port:' "${INFO_FILE}" 2>/dev/null | sed 's/^port:[[:space:]]*//' || true)"
[ -n "${PORT_SHOW}" ] || PORT_SHOW=8888

ensure_dir "${APP_PATH}"
cat >"${INFO_FILE}" <<EOF
instance: phpmyadmin
install_dir: ${INSTALL_DIR}
config_file: ${INSTALL_DIR}/config.inc.php
web_url: http://${HOST_IP}:${PORT_SHOW}
expose: port
port: ${PORT_SHOW}
tags:
  - webapp
  - mysql
EOF

log_ok "${APP_TITLE} ${VERSION} upgraded successfully"
log_info "Access URL: http://${HOST_IP}:${PORT_SHOW}"
