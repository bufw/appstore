#!/bin/bash
# phpMyAdmin install script (invoked by the zap appstore)
#
# Injected environment variables (provided by zapexec):
#   ZAP_PATH APPS_DIR PKG_PATH APP_PATH BUILD_PATH ZAP_DATA_PATH
#   APP_VERSION MAJOR_VERSION MINOR_VERSION CPU_NUM
# Options (app.yaml options.install, injected as same-named env vars):
#   PORT          access port (default 8888)
#   PHP_VERSION   runtime PHP (auto = auto-pick the highest installed version)
#   DB_HOST       managed database host (default 127.0.0.1)
#   DB_PORT       database port (default 3306)
set -euo pipefail

source "${ZAP_PATH}/scripts/zap/bash_utils.sh"
assert_root || exit 1

APP_TITLE="phpMyAdmin"

DB_HOST_OPT="${DB_HOST:-127.0.0.1}"
DB_PORT_OPT="${DB_PORT:-3306}"
PA_SHORT_VERSION="${MAJOR_VERSION}.${MINOR_VERSION}"
INSTALL_DIR="${APPS_DIR}/phpmyadmin-${PA_SHORT_VERSION}"
LINK_DIR="${APPS_DIR}/phpmyadmin"

LOG_DIR="${ZAP_DATA_PATH}/logs"

log_info "Preparing to install ${APP_TITLE}"

# ── download & extract ──────────────────────────────────────────────
ARCHIVE="phpMyAdmin-${APP_VERSION}-all-languages.tar.gz"
URL="$(pkg_mirror)/webapps/${ARCHIVE}"

rm -rf "${BUILD_PATH}"
ensure_dir "${BUILD_PATH}"
download_file "${URL}" "${BUILD_PATH}/${ARCHIVE}"
extract_archive "${BUILD_PATH}/${ARCHIVE}" "${BUILD_PATH}" || {
    log_error "Extraction failed: ${ARCHIVE}"
    exit 1
}

SRC_DIR="${BUILD_PATH}/phpMyAdmin-${APP_VERSION}-all-languages"
if [ ! -d "${SRC_DIR}" ]; then
    # A few versions ship with a different top-level directory name; fall back to the only subdir
    SRC_DIR="$(find "${BUILD_PATH}" -maxdepth 1 -mindepth 1 -type d | head -n1)"
fi
[ -d "${SRC_DIR}" ] || { log_error "Unexpected extraction result: source directory not found"; exit 1; }

# ── deploy to the install directory ──────────────────────────────────────────
if [ -d "${INSTALL_DIR}" ]; then
    BAK_DIR="${INSTALL_DIR}.bak.$(date +%s)"
    log_warn "Install directory already exists; backed it up to ${BAK_DIR}"
    mv "${INSTALL_DIR}" "${BAK_DIR}"
fi
ensure_dir "$(dirname "${INSTALL_DIR}")"
mv "${SRC_DIR}" "${INSTALL_DIR}"
ln -sfn "${INSTALL_DIR}" "${LINK_DIR}"
log_ok "Program deployed to: ${INSTALL_DIR}"

# ── generate config.inc.php ─────────────────────────────────────
ensure_dir "${INSTALL_DIR}/tmp" "${INSTALL_DIR}/upload" "${INSTALL_DIR}/save"
SECRET="$(random_password 32 | tr -d '\n')"
cat >"${INSTALL_DIR}/config.inc.php" <<EOF
<?php
/**
 * phpMyAdmin config (generated by the ZAP appstore; auto-generated, do NOT edit blowfish_secret by hand)
 * Generated at: $(date '+%Y-%m-%d %H:%M:%S')
 */
declare(strict_types=1);

\$cfg['blowfish_secret'] = '${SECRET}';
\$cfg['DefaultLang'] = 'zh_CN';
\$cfg['TempDir'] = '/tmp';
\$cfg['UploadDir'] = '${LINK_DIR}/upload';
\$cfg['SaveDir'] = '${LINK_DIR}/save';

\$i = 0;
\$i++;
\$cfg['Servers'][\$i]['host'] = '${DB_HOST_OPT}';
\$cfg['Servers'][\$i]['port'] = '${DB_PORT_OPT}';
\$cfg['Servers'][\$i]['auth_type'] = 'cookie';
\$cfg['Servers'][\$i]['AllowNoPassword'] = false;
EOF
log_ok "Generated config.inc.php (database ${DB_HOST_OPT}:${DB_PORT_OPT})"

# ── runtime user & permissions ──────────────────────────────────────────
RUN_USER="www"
id -u www >/dev/null 2>&1 || RUN_USER="nginx"
id -u "${RUN_USER}" >/dev/null 2>&1 || RUN_USER="$(id -un)"
chown -R "${RUN_USER}" "${INSTALL_DIR}" 2>/dev/null || log_warn "Failed to change owner (user ${RUN_USER}); please verify permissions manually"
find "${INSTALL_DIR}" -type d -exec chmod 0755 {} + 2>/dev/null || true
find "${INSTALL_DIR}" -type f -exec chmod 0644 {} + 2>/dev/null || true
chmod 0770 "${INSTALL_DIR}/tmp" "${INSTALL_DIR}/upload" "${INSTALL_DIR}/save" 2>/dev/null || true


# ── register instance info ────────────────────────────────────────────
HOST_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
[ -n "${HOST_IP}" ] || HOST_IP="$(ip route get 1 2>/dev/null | awk '{print $7; exit}')"
[ -n "${HOST_IP}" ] || HOST_IP="127.0.0.1"

ensure_dir "${APP_PATH}"
cat >"${APP_PATH}/info.yaml" <<EOF
instance: phpmyadmin
install_dir: ${INSTALL_DIR}
config_file: ${INSTALL_DIR}/config.inc.php
web_url: http://${HOST_IP}:2663/webapps/phpmyadmin/
expose: none
tags:
  - webapp
  - mysql
EOF

log_ok "${APP_TITLE} ${APP_VERSION} installed successfully"
log_info "Access URL: http://${HOST_IP}:2663/webapps/phpmyadmin/ (keep the trailing slash; log in with an existing MySQL / MariaDB account)"
